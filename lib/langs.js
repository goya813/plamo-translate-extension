/** <select> に言語の選択肢を入れる。`auto` を付けると「自動（日⇄英）」が先頭に入る。 */
export function fillLangSelect(select, { auto = false, value } = {}) {
  select.textContent = "";
  if (auto) select.add(new Option("自動（日本語 ⇄ 英語）", "auto"));
  for (const [code, name] of LANGS) select.add(new Option(`${name} (${code})`, code));
  if (value) select.value = value;
}
